import type { Difficulty, QuizQuestion, SubjectId } from "./types";

// Demonstration question bank. Quiz Studio samples from here until AI generation is connected.

type Row = [Difficulty, string, string[], number, string];

function topic(subjectId: SubjectId, topicId: string, rows: Row[]): QuizQuestion[] {
  return rows.map(([difficulty, prompt, options, answerIndex, explanation], i) => ({
    id: `${subjectId}-${topicId}-${i + 1}`,
    subjectId,
    topicId,
    difficulty,
    prompt,
    options,
    answerIndex,
    explanation,
  }));
}

